import os
import psycopg2
from psycopg2 import pool

db_pool = pool.SimpleConnectionPool(
    minconn=1,
    maxconn=10,
    dbname = os.getenv("DBNAME"),
    dbuser = os.getenv("DBUSER"),
    dbpassword = os.getenv("DBNPASSWORD"),
    dbhost = os.getenv("DBNHOST"),
    dbport = os.getenv("DBPORT")
)

def get_connection():
    return db_pool.getconn()

def release_connection(conn):
    db_pool.putconn(conn)

class Database:
    def __init__(self):
        try:
            conn = get_connection()
            self.connection = conn
        except psycopg2.Error as error:
            raise RuntimeError("Не удалось подключиться к БД") from error
        
        try:
            cursor = conn.cursor()
            cursor.execute('''
                            CREATE TABLE IF NOT EXISTS "objects" (
                                id INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
                                address TEXT
                            );
                            ''')
            cursor.execute('''
                CREATE TABLE IF NOT EXISTS "roles" (
                    id INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
                    role_name TEXT NOT NULL UNIQUE,
                    hourly_rate REAL NOT NULL
                );
                ''')
            cursor.execute('''
                            CREATE TABLE IF NOT EXISTS "employees" (
                                id INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
                                surname TEXT NOT NULL,
                                name TEXT NOT NULL,
                                patronymic TEXT NOT NULL,
                                object_id INTEGER NOT NULL REFERENCES objects(id),
                                role_id INTEGER NOT NULL REFERENCES roles(id)
                            );
                            ''')
            cursor.execute('''
                            CREATE TABLE IF NOT EXISTS "shifts" (
                                id INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
                                shift_date DATE NOT NULL,
                                start_shift TIME NOT NULL,
                                end_shift TIME NOT NULL,
                                hours REAL,
                                employee_id INTEGER NOT NULL REFERENCES employees(id),
                                revenue REAL
                            );
                            ''')
            conn.commit()
            cursor.close()
        except psycopg2.Error as error:
            conn.rollback()
            conn.close()
            raise RuntimeError("Не удалось создать таблицы БД") from error

    def close(self):
        self.connection.close()